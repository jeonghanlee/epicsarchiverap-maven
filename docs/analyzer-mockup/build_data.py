#!/usr/bin/env python3
"""Bundle the saved signal examples for direct local-file browser use."""

import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / "analyzer-signal-examples"
SCENARIOS = ("beam_current", "bpm", "magnet_supply", "rf_cavity", "vacuum",
             "temperature", "photon_counts", "camera")


def main():
    verification = json.loads((SOURCE / "verification.json").read_text())
    documents, hashes = {}, {}
    for name in SCENARIOS:
        relative = f"data/{name}.json"
        content = (SOURCE / relative).read_bytes()
        digest = hashlib.sha256(content).hexdigest()
        if digest != verification["data_sha256"][relative]:
            raise ValueError(f"Source data changed after verification: {relative}")
        documents[name] = json.loads(content)
        hashes[relative] = digest
    bundle = "/* Generated by build_data.py from the saved synthetic JSON files. */\n"
    bundle += "const SIGNAL_DOCUMENTS = " + json.dumps(documents, separators=(",", ":"), allow_nan=False) + ";\n"
    bundle += "const SIGNAL_SOURCE_HASHES = " + json.dumps(hashes, indent=2) + ";\n"
    (ROOT / "signal-data.js").write_text(bundle)
    print(f"Bundled {len(documents)} verified source documents ({len(bundle):,} bytes)")


if __name__ == "__main__":
    main()
