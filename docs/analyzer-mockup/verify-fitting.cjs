/* Exercise the real offline UI and preserve its downloaded fit results. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/tmp/analyzer-design-browser-20261104/node_modules/playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = __dirname;
const checks = [], errors = [];

(async () => {
    const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/home/jeonglee/.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell', args: ['--no-sandbox'] });
    try {
        const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
        page.on('pageerror', error => errors.push(error.message));
        const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
        const edit = async (id, value) => { await page.locator(`#${id}`).fill(String(value)); await page.locator(`#${id}`).press('Tab'); };
        const choose = async (example, recipe) => {
            await page.goto(`file://${root}/index.html`);
            await page.selectOption('#example', example);
            await page.locator(`[data-recipe="${recipe}"]`).click();
            await page.click('#panel-tab-Options');
        };
        const exportFit = async name => {
            await page.click('#run-fit');
            const status = await page.locator('#fit-status').innerText();
            check(`${name}: converged`, /Converged|Fixed parameters evaluated/.test(status));
            check(`${name}: curve and residuals`, await page.locator('.fit-curve').count() === 1 && await page.locator('.fit-residuals svg[data-chart-canvas]').count() === 1);
            check(`${name}: uncertainty columns visible`, (await page.locator('#fit-parameters').innerText()).includes('Std. error / 1 sigma') && (await page.locator('#fit-parameters').innerText()).includes('Approx. 95% interval'));
            await page.click('#panel-tab-Export');
            const downloading = page.waitForEvent('download');
            await page.click('#download-fit');
            const download = await downloading;
            const file = path.join(root, `fit-${name}.json`);
            await download.saveAs(file);
            const report = JSON.parse(fs.readFileSync(file));
            check(`${name}: finite export`, report.result.success && report.result.rows.every(row => Number.isFinite(row.fitted) && Number.isFinite(row.residual)));
            const uncertainty = report.result.uncertainty;
            check(`${name}: explicit uncertainty state`, ['estimated', 'fixed', 'unavailable'].includes(uncertainty.status) && typeof uncertainty.reason === 'string');
            check(`${name}: fixed errors are not zero estimates`, report.config.parameters.filter(parameter => parameter.fixed).every(parameter => uncertainty.parameters[parameter.name].status === 'fixed' && uncertainty.parameters[parameter.name].standardError === null));
            const csvDownload = page.waitForEvent('download');
            await page.click('#download-csv');
            await (await csvDownload).saveAs(path.join(root, `fit-${name}.csv`));
            const parameterDownload = page.waitForEvent('download');
            await page.click('#download-fit-parameters');
            await (await parameterDownload).saveAs(path.join(root, `fit-${name}-parameters.csv`));
            await page.click('#panel-tab-Options');
            return report;
        };
        await choose('temperature', 2);
        const gaussian = await exportFit('temperature-gaussian');
        check('Gaussian uses all bins including empty bins', gaussian.result.rows.length === 20 && gaussian.result.rows.some(row => row.y === 0));
        check('Gaussian physical scale', Math.abs(gaussian.result.parameters.mu - 25) < 0.01 && Math.abs(gaussian.result.parameters.sigma - 0.025) < 0.005);
        check('Gaussian count likelihood has parameter errors', gaussian.result.uncertainty.status === 'estimated' && gaussian.result.uncertainty.varianceScale === 1 && gaussian.result.uncertainty.parameters.mu.standardError > 0);
        await page.screenshot({ path: path.join(root, 'preview-histogram-fit.png'), fullPage: true });
        await edit('fit-low', 24.96);
        await edit('fit-high', 25.04);
        await edit('fit-param-sigma', 0.025);
        await page.locator('#fit-fixed-sigma').check();
        const histogramRange = await exportFit('temperature-range-fixed');
        check('Histogram range includes only complete bins', histogramRange.result.rows.length < 20 && histogramRange.result.rows.every(row => row.lower >= 24.96 && row.upper <= 25.04));
        check('Histogram fixed sigma is exact', histogramRange.result.parameters.sigma === 0.025);
        await page.selectOption('#fit-model', 'normal-background');
        const background = await exportFit('temperature-background');
        check('Background boundary suppresses covariance', background.result.uncertainty.status === 'unavailable' && background.result.uncertainty.covariance === null);
        await page.selectOption('#fit-objective', 'least-squares');
        await exportFit('temperature-least-squares');
        await page.selectOption('#fit-model', 'normal');
        await page.selectOption('#fit-objective', 'least-squares');
        const histogramOls = await exportFit('temperature-gaussian-ols');
        check('Histogram least squares scales residual variance', histogramOls.result.uncertainty.status === 'estimated' && histogramOls.result.uncertainty.varianceScale > 1);
        await page.selectOption('#fit-model', 'poisson');
        await page.click('#run-fit');
        check('Poisson rejects continuous units', (await page.locator('#fit-status').innerText()).includes('Poisson requires') && await page.locator('.fit-curve').count() === 0);

        await choose('photon_counts', 1);
        await page.selectOption('#fit-model', 'poisson');
        const poisson = await exportFit('photon-poisson');
        check('Poisson mean matches illumination', Math.abs(poisson.result.parameters.lambda - 80.5) < 1);
        check('Poisson errors use count variance without residual rescaling', poisson.result.uncertainty.status === 'estimated' && poisson.result.uncertainty.varianceScale === 1);
        await page.locator('[data-recipe="2"]').click();
        check('Changing interval clears fit', await page.locator('.fit-curve').count() === 0);
        await page.selectOption('#fit-model', 'poisson');
        const dark = await exportFit('dark-poisson');
        check('Dark-count fit includes zero', dark.result.rows.some(row => row.firstInteger === 0 && row.y > 0) && Math.abs(dark.result.parameters.lambda - 0.5) < 0.15);
        check('Poisson degrees of freedom excludes impossible bins', dark.result.df === dark.result.rows.filter(row => row.firstInteger <= row.lastInteger).length - dark.result.free);
        await edit('fit-high', 0.4);
        await page.click('#run-fit');
        check('Poisson requires enough possible integer bins', (await page.locator('#fit-status').innerText()).includes('bins containing possible integer outcomes') && await page.locator('.fit-curve').count() === 0);
        await page.selectOption('#bins', '40');
        check('Changing bins clears fit and preserves exact count', await page.locator('.fit-curve').count() === 0 && await page.locator('#chart-area svg rect:not([id])').count() >= 40);

        await choose('bpm', 1);
        const linear = await exportFit('bpm-linear');
        check('BPM slope has expected physical scale', Math.abs(linear.result.parameters.m - 6) < 0.2);
        check('Linear slope uncertainty and interval', linear.result.uncertainty.status === 'estimated' && linear.result.uncertainty.parameters.m.lower95 < linear.result.parameters.m && linear.result.uncertainty.parameters.m.upper95 > linear.result.parameters.m);
        await page.screenshot({ path: path.join(root, 'preview-correlation-fit.png'), fullPage: true });
        await page.locator('#fit-curve').uncheck();
        check('Curve visibility preserves result', await page.locator('.fit-curve').count() === 0 && (await page.locator('#fit-summary').innerText()).includes('Fit result'));
        await page.locator('#fit-curve').check();
        await page.locator('#fit-residuals').uncheck();
        check('Residual visibility preserves curve', await page.locator('.fit-residuals').count() === 0 && await page.locator('.fit-curve').count() === 1);
        await page.locator('#fit-residuals').check();
        await page.selectOption('#profile', 'mono');
        check('Display change preserves fit', await page.locator('.fit-curve').count() === 1);
        await page.selectOption('#fit-model', 'quadratic');
        await exportFit('bpm-quadratic');
        await page.selectOption('#fit-model', 'peak');
        await edit('fit-param-mu', 23);
        await page.locator('#fit-fixed-mu').check();
        await edit('fit-param-sigma', 0.2);
        await page.locator('#fit-fixed-sigma').check();
        const peak = await exportFit('bpm-gaussian-offset');
        check('Fixed parameters are exact', peak.result.parameters.mu === 23 && peak.result.parameters.sigma === 0.2);
        await edit('fit-param-a', 0);
        await page.locator('#fit-fixed-a').check();
        await page.locator('#fit-fixed-mu').uncheck();
        await page.locator('#fit-fixed-sigma').uncheck();
        await page.click('#run-fit');
        check('Undetermined parameters do not report success', (await page.locator('#fit-status').innerText()).includes('not independently determined') && await page.locator('.fit-curve').count() === 0);
        check('Undetermined fit has no uncertainty table', await page.locator('#fit-parameters').count() === 0);

        await page.selectOption('#fit-model', 'linear');
        await edit('fit-max-m', 5.97);
        const nearBound = await exportFit('bpm-near-bound');
        check('Near-bound intervals are withheld rather than clipped', nearBound.result.atBounds.length === 0 && nearBound.result.uncertainty.status === 'unavailable' && nearBound.result.uncertainty.reason.includes('reaches a parameter bound'));
        await edit('fit-param-m', 4);
        await edit('fit-max-m', 5);
        const bounded = await exportFit('bpm-bounded');
        check('Upper bound is enforced', bounded.result.parameters.m === 5 && bounded.result.atBounds.includes('m'));
        check('At-bound errors are unavailable for all free parameters', Object.values(bounded.result.uncertainty.parameters).every(parameter => parameter.standardError === null && parameter.status === 'unavailable'));
        await edit('fit-low', 22.9);
        await edit('fit-high', 23.1);
        const restricted = await exportFit('bpm-range');
        check('X range selects actual pairs', restricted.result.rows.length < linear.result.rows.length && restricted.result.rows.every(row => row.x >= 22.9 && row.x <= 23.1));
        await edit('fit-max-m', 3);
        await page.click('#run-fit');
        check('Invalid bounds report error without curve', (await page.locator('#fit-status').innerText()).includes('inside ordered bounds') && await page.locator('.fit-curve').count() === 0);
        await page.click('#reset-fit');
        check('Reset restores estimates and bounds', await page.inputValue('#fit-max-m') === '' && await page.locator('.fit-curve').count() === 0);
        await edit('fit-high', 22.6);
        await page.click('#run-fit');
        check('Invalid range rejected', (await page.locator('#fit-status').innerText()).includes('minimum must be smaller'));
        await page.click('#reset-fit');
        await edit('fit-param-m', 0);
        await page.locator('.fit-advanced summary').click();
        await edit('fit-iterations', 1);
        await page.click('#run-fit');
        check('Iteration limit is not success', (await page.locator('#fit-status').innerText()).includes('Iteration limit reached') && await page.locator('.fit-curve').count() === 0);
        check('Failed fit does not leave prior errors visible', await page.locator('#fit-parameters').count() === 0);
        await page.click('#reset-fit');
        await page.locator('#fit-fixed-m').check();
        await page.locator('#fit-fixed-b').check();
        const allFixed = await exportFit('bpm-all-fixed');
        check('All-fixed model has no covariance', allFixed.result.uncertainty.status === 'fixed' && allFixed.result.uncertainty.covariance === null);
        await page.click('#swap-signals');
        check('Swapping signals clears fit', await page.locator('.fit-curve').count() === 0);
        await page.selectOption('#demo-state', 'error');
        check('Request error hides fit controls and result', await page.locator('#run-fit').count() === 0 && await page.locator('.fit-curve').count() === 0);
        await page.selectOption('#demo-state', 'ready');

        await choose('photon_counts', 1);
        await page.fill('#pv-input', 'photon_counts.counts.count_rate_per_s');
        await page.locator('#pv-form button').click();
        await page.click('#tab-correlation');
        const exact = await exportFit('photon-exact-rate');
        check('Zero residual variance does not claim zero measurement uncertainty', exact.result.uncertainty.status === 'unavailable' && exact.result.uncertainty.reason.includes('Residual variance is zero'));

        await choose('temperature', 2);
        await page.click('#run-fit');
        for (const width of [1440, 720, 390, 320]) {
            await page.setViewportSize({ width, height: 1000 });
            await page.waitForTimeout(150);
            const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
            check(`Width ${width}: no page overflow`, !overflow);
            check(`Width ${width}: no invalid SVG`, !await page.locator('#chart-area').evaluate(node => /NaN|Infinity/.test(node.innerHTML)));
        }
        await page.screenshot({ path: path.join(root, 'preview-fit-mobile-320.png'), fullPage: true });
        check('No JavaScript errors', errors.length === 0);
        const report = { checks: checks.length, passed: checks, errors };
        fs.writeFileSync(path.join(root, 'fit-browser-check.json'), JSON.stringify(report, null, 2) + '\n');
        console.log(JSON.stringify(report));
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
